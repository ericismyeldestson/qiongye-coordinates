// Build our candidate set from licensed GeoNames data, never website bundles.
const fs=require('node:fs'),path=require('node:path'),zlib=require('node:zlib'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..'),source=path.join(root,'third_party/geonames/cities.json.gz');
const input=fs.readFileSync(source),raw=JSON.parse(zlib.gunzipSync(input));
const available=require('../miniprogram/data/cities'),byId=new Map(available.map(r=>[r[0],r]));
const populations=new Map(raw.cities.map(r=>[r[0],r[10]])),selected=new Map(),regions=new Map();
for(const row of available){
 const region=row[3];if(!regions.has(region))regions.set(region,[]);regions.get(region).push(row);
 if(populations.get(row[0])>=1000000)selected.set(row[0],row);
}
for(const rows of regions.values()){
 rows.sort((a,b)=>populations.get(b[0])-populations.get(a[0])||Number(a[0])-Number(b[0]));
 for(const row of rows.slice(0,2))selected.set(row[0],row);
}
for(const id of ['1819729','1821274','1668341']){
 if(!byId.has(id))throw Error('Required GeoNames city is absent: '+id);
 selected.set(id,byId.get(id));
}
const names=new Intl.DisplayNames(['zh-CN'],{type:'region'});
const regionName=code=>({CN:'中国',HK:'中国香港',MO:'中国澳门',TW:'中国台湾'}[code]||names.of(code));
const candidates=[...selected.values()].sort((a,b)=>Number(a[0])-Number(b[0])).map(r=>({id:r[0],name:r[2],displayName:r[1],country:r[3],countryName:regionName(r[3]),lat:r[4],lon:r[5]}));
const file='miniprogram/data/candidates.js';
const data='// GeoNames CC BY 4.0; generated by scripts/prepare-recommendations.cjs.\nmodule.exports='+JSON.stringify(candidates)+';\n';
fs.writeFileSync(path.join(root,file),data);
const manifest={method:'qy-geonames-million-plus-regional-top2-v1',source:'GeoNames cities5000, local licensed catalogue',sourceURL:'https://download.geonames.org/export/dump/',license:'CC-BY-4.0',sourceSha256:crypto.createHash('sha256').update(input).digest('hex'),candidateCount:candidates.length,chinaCandidateCount:candidates.filter(c=>['CN','HK','MO','TW'].includes(c.country)).length,selection:'Population >= 1,000,000 plus top two available cities per country/region; explicit HK, Macau and Taipei coverage; sort by GeoNames ID. Independently selected, not StarMapper data.',output:{file,sha256:crypto.createHash('sha256').update(data).digest('hex')}};
fs.writeFileSync(path.join(root,'recommendations-manifest.json'),JSON.stringify(manifest,null,2)+'\n');
console.log(JSON.stringify({candidateCount:manifest.candidateCount,chinaCandidateCount:manifest.chinaCandidateCount}));
