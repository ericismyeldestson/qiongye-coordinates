// Reproducibly select unchanged MIT-licensed functions from the official package.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..'),dir=path.join(root,'third_party/astronomy-engine');
const provenance=JSON.parse(fs.readFileSync(path.join(dir,'provenance.json')));
const sha=data=>crypto.createHash('sha256').update(data).digest('hex');
for(const item of provenance.files)if(sha(fs.readFileSync(path.join(dir,item.file)))!==item.sha256)throw Error('Astronomy Engine input changed: '+item.file);
const source=fs.readFileSync(path.join(dir,'astronomy.js'),'utf8');
function statement(prefix){const line=source.split('\n').find(line=>line.startsWith(prefix));if(!line)throw Error('Missing official declaration: '+prefix);return line;}
function block(type,name){
 const start=source.indexOf(type+' '+name+(type==='class'?' {':'(')),end=source.indexOf('\n}',start);
 if(start<0||end<0)throw Error('Missing official function: '+name);
 return source.slice(start,end+2);
}
const constants=['const DAYS_PER_TROPICAL_YEAR =','const J2000 =','const ASEC180 =','const ASEC360 =','const ASEC2RAD =','exports.DEG2RAD ='];
const names=['DeltaT_EspenakMeeus','TerrestrialTime','MakeTime','iau2000b','mean_obliq','e_tilt','era','sidereal_time','SiderealTime'];
const result=[fs.readFileSync(path.join(dir,'LICENSE'),'utf8'),
 '// Generated by scripts/prepare-astronomy.cjs from official astronomy-engine 2.1.19.\n// Selected time/orientation functions retain their original bodies and MIT notice.',
 "'use strict';",...constants.map(statement),
 statement('let DeltaT ='),statement('var cache_e_tilt;'),statement('let sidereal_time_cache;'),
 block('class','AstroTime'),...names.map(name=>block('function',name)),
 'exports.MakeTime=MakeTime;exports.e_tilt=e_tilt;exports.SiderealTime=SiderealTime;'].join('\n\n')+'\n';
const output='miniprogram/vendor/astronomy-time.js';fs.writeFileSync(path.join(root,output),result);
provenance.output={file:output,sha256:sha(result)};
fs.writeFileSync(path.join(dir,'provenance.json'),JSON.stringify(provenance,null,2)+'\n');
console.log(JSON.stringify({output,bytes:Buffer.byteLength(result)}));
